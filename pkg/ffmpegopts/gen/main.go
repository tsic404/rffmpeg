//go:build gen

// Command gen regenerates the FFmpeg option arity table in the parent
// package (ffmpegopts.go). Run `go generate ./pkg/ffmpegopts` after
// upgrading FFmpeg.
//
// It parses `ffmpeg -h long`: an option line whose description contains a
// value placeholder ("<...>") takes a value; a bare description or an empty
// placeholder ("<>") does not. Known-ambiguous lines are corrected via
// overrides in ffmpegopts.go.
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"regexp"
	"sort"
	"strings"
)

const target = "ffmpegopts.go"

var (
	lineRe  = regexp.MustCompile(`^\s*-(\S+?)(\[:<[^>]*>])?\s+(.*)$`)
	shortRe = regexp.MustCompile(`^\s*-[Lh]\s+`)
	entryRe = regexp.MustCompile(`"([^"]+)":`)
)

func main() {
	out, err := exec.Command("ffmpeg", "-hide_banner", "-h", "long").Output()
	if err != nil {
		fatal("run `ffmpeg -h long`: %v", err)
	}

	boolean := map[string]bool{}
	for _, line := range strings.Split(string(out), "\n") {
		if shortRe.MatchString(line) { // "-L", "-h <topic>" help block
			continue
		}
		m := lineRe.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		// m[3] is the description; the optional [:<stream_spec>] group is
		// captured separately and must be stripped from its head.
		desc := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(m[3]), m[2]))
		// A value placeholder ("<...>") means the option takes a value and
		// needs no table entry (arity is "not boolean"); a bare description
		// or an empty "<>" placeholder does not. The "<>" case is ambiguous
		// — genuine value options misprinted that way are corrected in the
		// overrides map of ffmpegopts.go.
		if strings.Contains(desc, "<") {
			continue
		}
		boolean[m[1]] = true
	}

	// Names hand-decided in ffmpegopts.go are skipped here so a regenerated
	// table cannot introduce duplicate map keys. The overrides live before
	// the GENERATED-START marker.
	handWritten := map[string]bool{}
	if data, err := os.ReadFile(target); err == nil {
		text := string(data)
		if idx := strings.Index(text, "// GENERATED-START"); idx >= 0 {
			for _, m := range entryRe.FindAllStringSubmatch(text[:idx], -1) {
				handWritten[m[1]] = true
			}
		}
	}

	var boolNames []string
	for name := range boolean {
		if !handWritten[name] {
			boolNames = append(boolNames, name)
		}
	}
	sort.Strings(boolNames)

	// Emit bare map entries; they are spliced between the GENERATED markers
	// inside the booleanFlags literal in ffmpegopts.go. Names already present
	// in the hand-written overrides section of that file are skipped so a
	// regenerated table cannot introduce duplicate keys.
	var buf bytes.Buffer
	buf.WriteString("\t// Code generated by gen/main.go from `ffmpeg -h long`; DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "\t// Regenerate with `go generate ./pkg/ffmpegopts` (%d boolean options).\n", len(boolNames))
	for _, name := range boolNames {
		fmt.Fprintf(&buf, "\t%q: true,\n", name)
	}
	if err := splice(buf.String(), "// GENERATED-START", "// GENERATED-END"); err != nil {
		fatal(err.Error())
	}

	// gofmt the whole target file afterwards; format.Source cannot parse a
	// bare fragment of map entries.
	if out, err := exec.Command("gofmt", "-w", target).CombinedOutput(); err != nil {
		fatal("gofmt %s: %v: %s", target, string(out))
	}
	fmt.Fprintf(os.Stderr, "gen: wrote %d boolean options into %s\n", len(boolNames), target)
	genMuxerTables()
}

var (
	// extRe extracts the comma-separated extension list from an
	// `ffmpeg -h muxer=<name>` "Common extensions:" line, e.g. "Common
	// extensions: bmp,jpg,png." -> "bmp,jpg,png".
	extRe = regexp.MustCompile(`Common extensions: ([^.]*)\.`)
	// videoCodecRe extracts the codec ffmpeg picks for a muxer when the output
	// request names no encoder, e.g. "Default video codec: vp9." -> "vp9".
	videoCodecRe = regexp.MustCompile(`Default video codec: ([^.]*)\.`)
)

// muxerInfo is one muxer's contribution to the generated tables.
type muxerInfo struct {
	name       string
	extensions []string
	videoCodec string
}

// genMuxerTables writes muxers_gen.go: the extension -> muxer guess table and
// the muxer -> default video codec table. Both derive from the same
// `ffmpeg -muxers` / `ffmpeg -h muxer=<name>` scan, mirroring how the arity
// table derives from `ffmpeg -h long`.
func genMuxerTables() {
	muxersOut, err := exec.Command("ffmpeg", "-hide_banner", "-muxers").Output()
	if err != nil {
		fatal("run `ffmpeg -muxers`: %v", err)
	}
	var muxers []muxerInfo
	for _, line := range strings.Split(string(muxersOut), "\n") {
		fields := strings.Fields(line)
		if len(fields) < 2 || fields[1] == "=" || !strings.Contains(fields[0], "E") {
			continue
		}
		muxer := muxerInfo{name: fields[1]}
		out, err := exec.Command("ffmpeg", "-hide_banner", "-h", "muxer="+muxer.name).Output()
		if err != nil {
			// A muxer listed by `ffmpeg -muxers` must have a help page. A
			// failure here means a transient error or an incompatible build;
			// silently skipping it would shrink the table without notice, so
			// fail instead of emitting a table the guard tests cannot fully
			// protect.
			fatal("run `ffmpeg -h muxer=%s`: %v", muxer.name, err)
		}
		if m := extRe.FindStringSubmatch(string(out)); m != nil {
			for _, ext := range strings.Split(m[1], ",") {
				if ext = strings.ToLower(strings.TrimSpace(ext)); ext != "" {
					muxer.extensions = append(muxer.extensions, ext)
				}
			}
		}
		if m := videoCodecRe.FindStringSubmatch(string(out)); m != nil {
			muxer.videoCodec = strings.ToLower(strings.TrimSpace(m[1]))
		}
		muxers = append(muxers, muxer)
	}

	// ffmpeg guesses an output format by walking the muxer registry in the
	// order `ffmpeg -muxers` lists it and taking the first muxer whose
	// extension list contains the filename extension. Registration order
	// decides the collisions: ".m4v" resolves to ipod (registered before the
	// raw m4v muxer) and ".vob" to svcd (registered before the vob muxer).
	extMuxer := map[string]string{}
	for _, muxer := range muxers {
		for _, ext := range muxer.extensions {
			if _, seen := extMuxer[ext]; !seen {
				extMuxer[ext] = muxer.name
			}
		}
	}

	codecs := map[string]string{}
	for _, muxer := range muxers {
		if muxer.videoCodec != "" {
			codecs[muxer.name] = muxer.videoCodec
		}
	}

	extNames := sortedKeys(extMuxer)
	muxerNames := sortedKeys(codecs)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gen/main.go from `ffmpeg -muxers` and `ffmpeg -h muxer=<name>`; DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "// Regenerate with `go generate ./pkg/ffmpegopts` (%d extensions, %d muxers with a default video codec).\n\n",
		len(extNames), len(muxerNames))
	buf.WriteString("package ffmpegopts\n\n")
	buf.WriteString("// extensionMuxer maps a lowercased filename extension (without the leading dot)\n")
	buf.WriteString("// to the muxer ffmpeg guesses for that output filename. Absent = ffmpeg cannot\n")
	buf.WriteString("// infer an output format from the extension.\n")
	buf.WriteString("var extensionMuxer = map[string]string{\n")
	for _, ext := range extNames {
		fmt.Fprintf(&buf, "\t%q: %q,\n", ext, extMuxer[ext])
	}
	buf.WriteString("}\n\n")
	buf.WriteString("// muxerDefaultVideoCodec maps a muxer name to the video codec native ffmpeg\n")
	buf.WriteString("// selects when the output request names no encoder. A muxer without such a\n")
	buf.WriteString("// codec cannot carry a video stream and is absent.\n")
	buf.WriteString("var muxerDefaultVideoCodec = map[string]string{\n")
	for _, name := range muxerNames {
		fmt.Fprintf(&buf, "\t%q: %q,\n", name, codecs[name])
	}
	buf.WriteString("}\n")

	const genFile = "muxers_gen.go"
	if err := os.WriteFile(genFile, buf.Bytes(), 0o644); err != nil {
		fatal("write %s: %v", genFile, err)
	}
	if out, err := exec.Command("gofmt", "-w", genFile).CombinedOutput(); err != nil {
		fatal("gofmt %s: %v: %s", genFile, err, string(out))
	}
	fmt.Fprintf(os.Stderr, "gen: wrote %d extensions and %d muxer video codecs into %s\n",
		len(extNames), len(muxerNames), genFile)
}

// sortedKeys returns the map's keys in sorted order.
func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// splice replaces everything strictly between the startMark and endMark
// marker lines, keeping both markers in place so generation is idempotent.
func splice(generated, startMark, endMark string) error {
	data, err := os.ReadFile(target)
	if err != nil {
		return err
	}
	text := string(data)
	start := strings.Index(text, startMark)
	if start < 0 {
		return fmt.Errorf("marker %q not found in %s", startMark, target)
	}
	// Skip to the end of the START marker's line.
	nl := strings.IndexByte(text[start:], '\n')
	if nl < 0 {
		return fmt.Errorf("marker line %q not terminated", startMark)
	}
	bodyStart := start + nl + 1
	end := strings.Index(text, endMark)
	if end < bodyStart {
		return fmt.Errorf("marker %q not found after %q in %s", endMark, startMark, target)
	}
	out := text[:bodyStart] + strings.TrimRight(generated, "\n") + "\n" + text[end:]
	return os.WriteFile(target, []byte(out), 0o644)
}

func fatal(formatStr string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen: "+formatStr+"\n", args...)
	os.Exit(1)
}
