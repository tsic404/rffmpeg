//go:build gen

// Command gen regenerates the FFmpeg option arity table in the parent
// package (ffmpegopts.go). Run `go generate ./pkg/ffmpegopts` after
// upgrading FFmpeg.
//
// It parses `ffmpeg -h long`: an option line whose description contains a
// value placeholder ("<...>") takes a value; a bare description or an empty
// placeholder ("<>") does not. Known-ambiguous lines are corrected via
// overrides in ffmpegopts.go.
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"regexp"
	"sort"
	"strings"
)

const target = "ffmpegopts.go"

var (
	lineRe  = regexp.MustCompile(`^\s*-(\S+?)(\[:<[^>]*>])?\s+(.*)$`)
	shortRe = regexp.MustCompile(`^\s*-[Lh]\s+`)
	entryRe = regexp.MustCompile(`"([^"]+)":`)
)

func main() {
	out, err := exec.Command("ffmpeg", "-hide_banner", "-h", "long").Output()
	if err != nil {
		fatal("run `ffmpeg -h long`: %v", err)
	}

	boolean := map[string]bool{}
	value := map[string]bool{}
	for _, line := range strings.Split(string(out), "\n") {
		if shortRe.MatchString(line) { // "-L", "-h <topic>" help block
			continue
		}
		m := lineRe.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		// m[3] is the description; the optional [:<stream_spec>] group is
		// captured separately and must be stripped from its head.
		desc := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(m[3]), m[2]))
		// A value placeholder ("<...>") means the option takes a value; a bare
		// description or an empty "<>" placeholder does not. The "<>" case is
		// ambiguous — genuine value options misprinted that way are fixed in
		// the overrides map of ffmpegopts.go.
		takesValue := strings.Contains(desc, "<")
		if takesValue {
			value[m[1]] = true
		} else {
			boolean[m[1]] = true
		}
	}

	// Names hand-decided in ffmpegopts.go are skipped here so a regenerated
	// table cannot introduce duplicate map keys. Two regions hold them: the
	// booleanFlags overrides (before GENERATED-START) and the valueFlags
	// corrections (between the booleanFlags GENERATED-END and
	// GENERATED-VALUE-START markers).
	handWritten := map[string]bool{}
	if data, err := os.ReadFile(target); err == nil {
		text := string(data)
		if idx := strings.Index(text, "// GENERATED-START"); idx >= 0 {
			for _, m := range entryRe.FindAllStringSubmatch(text[:idx], -1) {
				handWritten[m[1]] = true
			}
		}
		if start := strings.Index(text, "// GENERATED-VALUE-START"); start >= 0 {
			end := strings.LastIndex(text[:start], "// GENERATED-END")
			if end >= 0 {
				for _, m := range entryRe.FindAllStringSubmatch(text[end:start], -1) {
					handWritten[m[1]] = true
				}
			}
		}
	}

	var boolNames []string
	for name := range boolean {
		if !handWritten[name] {
			boolNames = append(boolNames, name)
		}
	}
	sort.Strings(boolNames)

	var valueNames []string
	for name := range value {
		if !handWritten[name] {
			valueNames = append(valueNames, name)
		}
	}
	sort.Strings(valueNames)

	// Emit bare map entries; they are spliced between the GENERATED markers
	// inside the booleanFlags / valueFlags literals in ffmpegopts.go. Names
	// already present in the hand-written overrides section of that file are
	// skipped so a regenerated table cannot introduce duplicate keys.
	var buf bytes.Buffer
	buf.WriteString("\t// Code generated by gen/main.go from `ffmpeg -h long`; DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "\t// Regenerate with `go generate ./pkg/ffmpegopts` (%d boolean options).\n", len(boolNames))
	for _, name := range boolNames {
		fmt.Fprintf(&buf, "\t%q: true,\n", name)
	}
	if err := splice(buf.String(), "// GENERATED-START", "// GENERATED-END"); err != nil {
		fatal(err.Error())
	}

	var vbuf bytes.Buffer
	vbuf.WriteString("\t// Code generated by gen/main.go from `ffmpeg -h long`; DO NOT EDIT.\n")
	fmt.Fprintf(&vbuf, "\t// Regenerate with `go generate ./pkg/ffmpegopts` (%d value-taking options).\n", len(valueNames))
	for _, name := range valueNames {
		fmt.Fprintf(&vbuf, "\t%q: true,\n", name)
	}
	if err := splice(vbuf.String(), "// GENERATED-VALUE-START", "// GENERATED-VALUE-END"); err != nil {
		fatal(err.Error())
	}

	// gofmt the whole target file afterwards; format.Source cannot parse a
	// bare fragment of map entries.
	if out, err := exec.Command("gofmt", "-w", target).CombinedOutput(); err != nil {
		fatal("gofmt %s: %v: %s", target, string(out))
	}
	fmt.Fprintf(os.Stderr, "gen: wrote %d boolean, %d value-taking options into %s\n", len(boolNames), len(valueNames), target)
}

// splice replaces everything strictly between the startMark and endMark
// marker lines, keeping both markers in place so generation is idempotent.
func splice(generated, startMark, endMark string) error {
	data, err := os.ReadFile(target)
	if err != nil {
		return err
	}
	text := string(data)
	start := strings.Index(text, startMark)
	if start < 0 {
		return fmt.Errorf("marker %q not found in %s", startMark, target)
	}
	// Skip to the end of the START marker's line.
	nl := strings.IndexByte(text[start:], '\n')
	if nl < 0 {
		return fmt.Errorf("marker line %q not terminated", startMark)
	}
	bodyStart := start + nl + 1
	end := strings.Index(text, endMark)
	if end < bodyStart {
		return fmt.Errorf("marker %q not found after %q in %s", endMark, startMark, target)
	}
	out := text[:bodyStart] + strings.TrimRight(generated, "\n") + "\n" + text[end:]
	return os.WriteFile(target, []byte(out), 0o644)
}

func fatal(formatStr string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen: "+formatStr+"\n", args...)
	os.Exit(1)
}
