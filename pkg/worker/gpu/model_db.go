// resolveModelName returns the readable model name for a PCI vendor/device id
// pair, or "" when the pair is unknown.
func resolveModelName(vendorID, deviceID string) string {
	return gpuModelNames[normalizePCID(vendorID)+":"+normalizePCID(deviceID)]
}

// normalizePCID lowercases a sysfs PCI id ("0x9BC5\n") into the table's key
// form ("9bc5").
func normalizePCID(id string) string {
	id = strings.TrimSpace(id)
	id = strings.TrimPrefix(id, "0x")
	id = strings.TrimPrefix(id, "0X")
	return strings.ToLower(id)
}
